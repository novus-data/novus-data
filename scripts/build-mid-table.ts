/**
 * Builds src/lib/live/mid-table.ts — Maritime Identification Digits to
 * country — from a copy of the ITU's table.
 *
 *   npx tsx scripts/build-mid-table.ts <mids.txt> --retrieved YYYY-MM-DD [--url <page>]
 *
 * WHY A SCRIPT AND NOT A TYPED-IN TABLE
 *
 * "Flag (from MMSI)" is only as good as the table behind it, and Rule 3 says
 * an embedded table must cite its source and retrieval date. The vessel layer
 * was written somewhere the ITU's site could not be reached, so rather than
 * type ~290 rows from memory, this turns the real list into the module, with
 * its provenance written into the file.
 *
 * HOW TO GET THE INPUT
 *
 * 1. Open https://www.itu.int/en/ITU-R/terrestrial/fmd/Pages/mid.aspx (the
 *    ITU's "Table of Maritime Identification Digits").
 * 2. Select the table, copy it, and paste it into a plain text file. Browsers
 *    copy a table as one row per line, cells separated by tabs. Each line the
 *    script uses must start with a three-digit MID followed by the country or
 *    area; any other line (headers, notes) is ignored and counted.
 * 3. Run the script with the date you copied it. Review the diff before
 *    committing: every MID in it should be on the ITU page.
 *
 * It refuses a file with fewer than 150 MIDs (a partial copy), a MID outside
 * 201–775, or a MID listed twice with different countries.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { blocker, detail, isIsoDate, ok, warn } from './lib/cli';

const DEFAULT_URL = 'https://www.itu.int/en/ITU-R/terrestrial/fmd/Pages/mid.aspx';
const OUT = path.join('src', 'lib', 'live', 'mid-table.ts');
const MIN_ROWS = 150;

function arg(name: string): string | null {
  const at = process.argv.indexOf(name);
  return at > 0 ? (process.argv[at + 1] ?? null) : null;
}

/** Parse the pasted table. Exported for the test. */
export function parseMidTable(text: string): { table: Record<string, string>; ignored: number; errors: string[] } {
  const table: Record<string, string> = {};
  const errors: string[] = [];
  let ignored = 0;
  for (const raw of text.split(/\r?\n/)) {
    const match = raw.match(/^\s*(\d{3})\s+(.+?)\s*$/);
    if (!match) {
      if (raw.trim()) ignored += 1;
      continue;
    }
    const [, mid, rawCountry] = match;
    const country = rawCountry.replace(/\s+/g, ' ').replace(/[\u0000-\u001F\u007F]/g, '').trim();
    const value = Number(mid);
    if (value < 201 || value > 775) {
      errors.push(`MID ${mid} is outside 201–775.`);
      continue;
    }
    if (table[mid] && table[mid] !== country) {
      errors.push(`MID ${mid} is listed twice: "${table[mid]}" and "${country}".`);
      continue;
    }
    table[mid] = country;
  }
  return { table, ignored, errors };
}

async function main(): Promise<void> {
  const input = process.argv[2];
  const retrieved = arg('--retrieved');
  const url = arg('--url') ?? DEFAULT_URL;
  if (!input || input.startsWith('--') || !retrieved || !isIsoDate(retrieved)) {
    blocker('Usage: npx tsx scripts/build-mid-table.ts <mids.txt> --retrieved YYYY-MM-DD [--url <page>]');
    process.exitCode = 1;
    return;
  }
  if (!/^https:\/\/(www\.)?itu\.int\//.test(url)) {
    blocker('--url must be a page on itu.int: the table is cited to the ITU, not to a copy of it.');
    process.exitCode = 1;
    return;
  }

  const { table, ignored, errors } = parseMidTable(await readFile(input, 'utf8'));
  for (const error of errors) blocker(error);
  const rows = Object.keys(table).length;
  if (errors.length > 0 || rows < MIN_ROWS) {
    if (rows < MIN_ROWS) blocker(`Only ${rows} MIDs found; the ITU table has far more. Copy the whole table.`);
    process.exitCode = 1;
    return;
  }
  if (ignored > 0) warn(`${ignored} non-table lines ignored.`);

  const body = Object.keys(table)
    .sort()
    .map((mid) => `  '${mid}': ${JSON.stringify(table[mid])},`)
    .join('\n');
  const file = `/**
 * Maritime Identification Digits → country or geographical area.
 *
 * GENERATED by scripts/build-mid-table.ts from the ITU's Table of Maritime
 * Identification Digits. Do not hand-edit: regenerate it, so the source and
 * retrieval date below always describe what is in the table.
 *
 * Source: ${url}
 * Retrieved: ${retrieved}. ${rows} MIDs.
 *
 * A MID says where an MMSI was issued, which usually but not always matches
 * the flag state; see flagFromMmsi in ./vessels.ts. Pure data; safe anywhere.
 */

export const MID_TABLE_SOURCE: { url: string; retrievedAt: string } | null = {
  url: ${JSON.stringify(url)},
  retrievedAt: ${JSON.stringify(retrieved)},
};

export const MID_TABLE: Readonly<Record<string, string>> = {
${body}
};
`;
  await writeFile(OUT, file);
  ok(`Wrote ${OUT}: ${rows} MIDs, retrieved ${retrieved}.`);
  detail('Review the diff, run npm run test:regressions, then commit.');
}

if (process.argv[1] && path.basename(process.argv[1]).startsWith('build-mid-table')) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
